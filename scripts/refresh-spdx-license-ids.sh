# refresh-spdx-license-ids.sh — regenerate priv/spdx/license-ids.txt from a
# tagged release of the SPDX License List (spdx/license-list-data).
#
# Hypatia.SPDX reads that file at compile time to decide whether a REUSE
# `LICENSES/<id>.<ext>` file names a real licence. The list grows with each
# SPDX release, so refresh it when a new tag appears:
#
#     scripts/refresh-spdx-license-ids.sh v3.29.0
#
# Then rebuild (`mix compile`) and commit the regenerated file. Deprecated
# identifiers are kept: older repositories still ship `LICENSES/GPL-3.0.txt`.

set -euo pipefail

TAG="${1:?usage: $0 <license-list-data tag, e.g. v3.29.0>}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${ROOT}/priv/spdx/license-ids.txt"
URL="https://raw.githubusercontent.com/spdx/license-list-data/${TAG}/json/licenses.json"

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

curl -sSfL --max-time 60 -o "$TMP" "$URL"

# Fail loudly on a malformed or unexpectedly small download rather than
# shipping a list that would reject real licences.
COUNT="$(jq '.licenses | length' "$TMP")"
if [ "$COUNT" -lt 500 ]; then
    echo "error: ${URL} lists only ${COUNT} licences; refusing to write it" >&2
    exit 1
fi

VERSION="$(jq -r '.licenseListVersion' "$TMP")"
RELEASED="$(jq -r '.releaseDate' "$TMP")"

mkdir -p "$(dirname "$OUT")"
{
    echo "# SPDX License List ${VERSION} (released ${RELEASED}): licence identifiers, one per line."
    echo "# Source: ${URL}"
    echo "# Generated by scripts/refresh-spdx-license-ids.sh; do not edit by hand."
    jq -r '.licenses[].licenseId' "$TMP" | LC_ALL=C sort -u
} > "$OUT"

echo "wrote ${OUT}: ${COUNT} identifiers from SPDX License List ${VERSION}"
